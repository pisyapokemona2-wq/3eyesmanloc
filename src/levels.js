'use strict';
// Уровни из ASCII-кусков (по 17 строк = высота экрана, кроме вертикальных секций).
// Все куски выравниваются по низу. Земля — нижние 3 строки, герой стоит на строке 13.
//
// ТАЙЛЫ:  # земля   = сквозная платформа   B кирпич (ломают копьё/выстрел/голова)
//         X окованный блок (только удар сверху)   Z треснувшая стена (рывок или удар сверху)
//         I лёд   ^ шипы   v шипы с потолка   F осыпающаяся плита   ~ жидкость   : задняя стена
//         ? бонус-монета  ! бонус-сердце  * бонус-энергия  & бонус-жизнь
// ПРЕДМЕТЫ: o монета  O / $ большая монета  H сердце  e энергия глаза  L жизнь
//         K чекпоинт  S пружина  M платформа ←→  N платформа ↑↓  U восходящий поток
//         T табличка  i факел  D пропс декора   P старт   @ вход на арену
// ВРАГИ:  w бесёнок  r крыса  l слизь  f лягушка  h ёж  t каменная голова  k страж со щитом
//         y йети  q пингвин  b летучая мышь  x ворона  g призрак  p огненный дух  j пиранья
//         m монах  n дрон  a гарпия  s паучок  c кристалл на потолке

const GROUND = (w, ch = '#') => [ch.repeat(w), ch.repeat(w), ch.repeat(w)];
// pad: дополняет строки до одинаковой ширины
const CH = (rows) => {
  const w = Math.max(...rows.map((r) => r.length));
  return rows.map((r) => r.padEnd(w, '.'));
};
// SEC: кусок с тайниками — прямоугольники [x, y, w, h], скрытые ложной стеной
const SEC = (rows, ...covers) => { const r = CH(rows); r.covers = covers; return r; };

// Арены: 30×17, правая стена, вход слева (закрывается решёткой)
function arena(o = {}) {
  const W = 30, rows = [];
  for (let y = 0; y < 14; y++) rows.push('.'.repeat(W - 1) + '#');
  const put = (y, x, s) => { rows[y] = rows[y].slice(0, x) + s + rows[y].slice(x + s.length); };
  for (const [y, x, len, ch] of o.plats || []) put(y, x, (ch || '=').repeat(len));
  put(13, 2, '@');
  for (let y = 14; y < 17; y++) {
    let r = '#'.repeat(W);
    for (const [a, b] of o.pools || []) r = r.slice(0, a) + '~'.repeat(b - a + 1) + r.slice(b + 1);
    rows.push(r);
  }
  if (o.bg) for (let y = 0; y < 14; y++) rows[y] = rows[y].split('').map((c, i) => (c === '.' && i > 0 ? ':' : c)).join('');
  return rows;
}

