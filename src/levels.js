  put(18, 5, '====');
  put(15, 9, '====');
  for (let y = 13; y <= 15; y++) put(y, 14, '#'.repeat(21));
  for (let y = 16; y <= 20; y++) put(y, 14, ':'.repeat(21)); // тоннель
